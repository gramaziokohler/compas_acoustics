"""Markdown for the generated pages. Links and images are relative to the page, as MkDocs reads them."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Callable

from .examples import Example
from .examples import walkthrough as read_walkthrough
from .specs import Component
from .specs import Port

GENERATED = "\n<!-- This page is generated by docs/_ext/ghcomponents; edit its sources, not this file. -->\n"


def escape(text: str) -> str:
    """Text that renders literally in Markdown."""
    return re.sub(r"([\\*`_|\[\]<>])", r"\\\1", str(text))


def cell(text: str) -> str:
    """Text on one line, literal, and not read as the start of a list or heading."""
    return re.sub(r"^([-+*#]|\d+\.)(\s)", r"\\\1\2", escape(" ".join(str(text).split())))


def title(text: str, level: int = 1) -> str:
    return "{} {}\n".format("#" * level, text)


def first_sentence(text: str) -> str:
    match = re.match(r"(.+?\.)(\s|$)", text.strip(), re.S)
    return match.group(1) if match else text.strip()


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def _input_row(p: Port) -> list[str]:
    description = cell(p.description)
    if p.choices:
        description += " Choices: " + ", ".join(escape(c) for c in p.choices) + "."
    if p.optional:
        description += " *Optional.*"
    default = "" if p.default is None else "`{}`".format(json.dumps(p.default) if isinstance(p.default, str) else p.default)
    return ["`{}`".format(p.name), escape(p.type_hint or ""), p.access, default, description.strip()]


def component_page(c: Component, *, image: str, icon: str, notes: Path | None, used_in: list[str], python: str | None) -> str:
    parts = [
        title(c.name),
        '![{} icon]({}){{ width="48" }}\n'.format(escape(c.name), icon),
        "{} · {}\n".format(escape(c.subcategory), escape(c.nickname)),
        cell(c.description) + "\n",
        "![{} on the Grasshopper canvas]({})\n".format(escape(c.name), image),
        title("Inputs", 2),
    ]
    if c.inputs:
        parts.append(_table(["Name", "Type", "Access", "Default", "Description"], [_input_row(p) for p in c.inputs]))
    else:
        parts.append("None.\n")
    parts.append(title("Outputs", 2))
    if c.outputs:
        parts.append(_table(["Name", "Description"], [["`{}`".format(p.name), cell(p.description)] for p in c.outputs]))
    else:
        parts.append("None.\n")
    if notes is not None:
        parts += [title("Notes", 2), Path(notes).read_text(encoding="utf-8").strip() + "\n"]
    if used_in:
        parts += [title("Used in", 2), "".join("* [{0}](../examples/{0}.md)\n".format(n) for n in used_in)]
    parts.append(title("Python equivalent", 2))
    parts.append("[`{0}`][{0}]\n".format(python) if python else "No Python equivalent (Grasshopper only).\n")
    return "\n".join(parts) + GENERATED


def overview_page(components: list[Component], order: list[str], icon_for: Callable[[Component], str]) -> str:
    parts = [title("Components"), "Every component of the plugin, by ribbon panel. Each page lists its inputs and outputs.\n"]
    for subcategory in order:
        members = [c for c in components if c.subcategory == subcategory]
        if not members:
            continue
        parts.append(title(subcategory, 2))
        cards = ['<div class="grid cards" markdown>\n']
        for c in members:
            cards += [
                '-   ![{0} icon]({1}){{ .ca-component-icon }} **[{0}]({2}.md)**\n'.format(escape(c.name), icon_for(c), c.key),
                "    ---\n",
                "    `{}` · {}\n".format(c.nickname, cell(first_sentence(c.description))),
            ]
        cards.append("</div>\n")
        parts.append("\n".join(cards))
    return "\n".join(parts) + GENERATED


def python_example_page(ex: Example, title_text: str, body: str, figures: list[str], stdout: str | None) -> str:
    parts = [title(title_text), body + "\n"]
    if ex.ghx is not None:
        parts.append("The same example in [Grasshopper](../../grasshopper/examples/{}.md).\n".format(ex.name))
    parts.append('```python\n--8<-- "examples/{}.py"\n```\n'.format(ex.name))
    if figures or stdout:
        parts.append(title("Output", 2))
        parts += ["![]({})\n".format(f) for f in figures]
        if stdout:
            parts.append("```text\n" + stdout.rstrip("\n") + "\n```\n")
    return "\n".join(parts) + GENERATED


def ghx_example_page(ex: Example, walkthrough: Path, download: str, canvas: str, viewport: str) -> str:
    title_text, body = read_walkthrough(walkthrough)
    intro, _, steps = body.partition("\n\n")
    parts = [
        title(title_text),
        intro + "\n",
        "Download the definition: [{}.ghx]({})\n".format(ex.name, download),
        "![The definition on the Grasshopper canvas]({})\n".format(canvas),
        "![The Rhino viewport]({})\n".format(viewport),
    ]
    if steps.strip():
        parts += [title("Walkthrough", 2), steps.strip() + "\n"]
    if ex.py is not None:
        parts.append("The same example in [Python](../../python/examples/{}.md).\n".format(ex.name))
    return "\n".join(parts) + GENERATED


def examples_index(title_text: str, names_titles: list[tuple[str, str]]) -> str:
    parts = [title(title_text), "".join("* [{}]({}.md)\n".format(t, name) for name, t in names_titles)]
    return "\n".join(parts) + GENERATED
