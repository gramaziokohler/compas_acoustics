# what the installer copies into Grasshopper's Libraries folder (installer/installer.py GHA_FILES)
GHA_FILES = ["CompasAcoustics.gha", "CompasPb.dll", "Google.Protobuf.dll", "Newtonsoft.Json.dll"]


@task
def generate_csharp(ctx):
    """Generate the C# bindings of compas_acoustics.pb for the Grasshopper plugin, and the schema hash it checks the worker against."""
    from compas_pb.invocations import setup_protoc

    from compas_acoustics.pb import schema_hash

    protoc, _ = setup_protoc()
    out = os.path.join(PLUGIN, "Generated")
    with ctx.cd(ctx.base_folder):
        includes = " ".join('--proto_path="{}"'.format(p) for p in ctx.proto_include_paths)
        for proto in sorted(glob.glob(os.path.join(ctx.proto_folder, "*.proto"))):
            ctx.run('"{}" {} --csharp_out="{}" "{}"'.format(protoc, includes, out, proto))
        with open(os.path.join(out, "Schema.cs"), "w") as f:
            f.write(
                "// Generated by `invoke generate-csharp`: the hash of compas_acoustics.pb's .proto files, which the worker reports.\n"
                "namespace CompasAcoustics.Grasshopper\n{\n"
                "    internal static class Schema\n    {\n"
                '        public const string Hash = "' + schema_hash() + '";\n'
                "    }\n}\n"
            )


